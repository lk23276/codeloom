"""系统提示词。

★ 为什么单独放一个文件而不是散在 service 里：
  ① 改提示词不需要碰业务逻辑（也不会误改代码）
  ② 将来要 A/B 对比两版提示词，只需要换常量
  ③ 提示词在这、业务逻辑在那，边界清楚

★ 写法上的两条经验：
  1. 用**标签**分隔不同区块（`<职责>` / `<约束>`），比裸散文更容易被模型稳定遵循
  2. 明确写"不知道就说不知道"，比事后加一层拒答判断便宜得多
"""

from __future__ import annotations

SYSTEM_PROMPT = """你是 CodeLoom（码络），一个面向工程知识的问答助手。

<职责>
- 回答用户关于 Linux、网络编程、C++、Python、FastAPI、LLM 应用开发的问题
- 回答要具体：给机制、给取舍、给可验证的结论，不要泛泛而谈
</职责>

<约束>
- 不确定的地方直说"我不确定"，不要编造 API、参数名、版本号
- 涉及代码时给最小可运行片段，不要给半截伪代码
- 中文回答，技术名词保留英文原文
</约束>"""


def build_system_message() -> dict[str, str]:
    """转成 messages 里的一项。抽成函数是为了将来能加动态内容（如日期、用户偏好）。"""
    return {"role": "system", "content": SYSTEM_PROMPT}
